'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const verifiedAnswers = JSON.parse(fs.readFileSync(
  path.join(root, 'src', 'tampermonkey', 'verified-answers.json'), 'utf8'
));
if (!Array.isArray(verifiedAnswers) || verifiedAnswers.some(entry =>
  !Array.isArray(entry) || entry.length < 2 || !entry[0] || !entry[1]
)) {
  throw new Error('src/tampermonkey/verified-answers.json 格式不正确');
}
const core = fs.readFileSync(path.join(root, 'src', 'shared', 'core.js'), 'utf8').trim();
const runtime = fs.readFileSync(path.join(root, 'src', 'tampermonkey', 'runtime.js'), 'utf8')
  .trim()
  .replace(/__PACKAGE_VERSION__/g, pkg.version)
  .replace('__VERIFIED_ANSWER_DATA__', JSON.stringify(verifiedAnswers));
const target = path.join(root, 'src', 'tampermonkey', 'hua-yi-helper.user.js');

const metadata = `// ==UserScript==
// @name         华医网学习助手 v6
// @namespace    https://github.com/wzgrx/hua-yi-helper
// @version      ${pkg.version}
// @description  华医网年度 5+20 学分智能规划、断点恢复与跨页面自动学习助手
// @author       wzgrx
// @license      AGPL-3.0
// @match        *://*.91huayi.com/*
// @run-at       document-idle
// @noframes
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_deleteValue
// @grant        GM_registerMenuCommand
// @grant        GM_xmlhttpRequest
// @grant        unsafeWindow
// @connect      127.0.0.1
// @connect      localhost
// @downloadURL  https://raw.githubusercontent.com/wzgrx/hua-yi-helper/main/src/tampermonkey/hua-yi-helper.user.js?v=${pkg.version}
// @updateURL    https://raw.githubusercontent.com/wzgrx/hua-yi-helper/main/src/tampermonkey/hua-yi-helper.user.js?v=${pkg.version}
// ==/UserScript==`;

const banner = `\n\n// Generated by scripts/build-userscript.js. Edit src/shared/core.js or src/tampermonkey/runtime.js.\n`;
fs.writeFileSync(target, `${metadata}${banner}${core}\n\n${runtime}\n`, 'utf8');
console.log(`Built ${path.relative(root, target)} (${pkg.version})`);
