    if (/exam\.aspx$/.test(path)) return 'exam';
    if (/\/course_ware\/course_ware(?:_(?:polyv|cc))?\.aspx$/.test(path)) return 'player';
    if (/\/course_ware\/course_list\.aspx$/.test(path)) return 'course';
