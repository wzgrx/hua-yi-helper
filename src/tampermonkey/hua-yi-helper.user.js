  function mergeRecords(left, right) {
    var map = {};
    (left || []).concat(right || []).forEach(function (record) {
      var normalizedRecord = Core.normalizeRecord(record, policy);
      var key = normalizedRecord.id || normalizedRecord.url || normalize(normalizedRecord.name);
      if (!key) return;
      map[key] = Object.assign({}, map[key] || {}, normalizedRecord);
    });
    return Object.keys(map).map(function (key) { return map[key]; });
  }

